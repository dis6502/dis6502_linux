bool InstructionSet::IsDualAddressingMode(byte opcode) const {
    return opcode == 0xAD || opcode == 0xBD // LDA
        || opcode == 0xAE || opcode == 0xBE // LDX
        || opcode == 0xAC || opcode == 0xBC // LDY
        || opcode == 0x8D || opcode == 0x9D // STA
        || opcode == 0x8E                   // STX
        || opcode == 0x8C                   // SYY
        || opcode == 0x2C                   // BIT
        || opcode == 0x6D || opcode == 0x7D // ADC
        || opcode == 0xED || opcode == 0xFD // SBC
        || opcode == 0x0E || opcode == 0x1E // ASL
        || opcode == 0x4E || opcode == 0x5E // LSR
        || opcode == 0x2E || opcode == 0x3E // ROL
        || opcode == 0x6E || opcode == 0x7E // ROR
        || opcode == 0xCE || opcode == 0xDE // DEC
        || opcode == 0xEE || opcode == 0xFE // INC
        || opcode == 0x0D || opcode == 0x1D // ORA
        || opcode == 0x2D || opcode == 0x3D // AND
        || opcode == 0x4D || opcode == 0x5D // EOR
        ;
}
