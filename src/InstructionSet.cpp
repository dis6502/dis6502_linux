#include "InstructionSet.h"


Instruction::Instruction(byte opcode, wstring_view name, bool illegal, LabelAccess labelAccess, OperandMode mode) : opcode(opcode), name(name), illegal(illegal), labelAccess(labelAccess), mode(mode) {

};


byte Instruction::GetOpcode() const {
    return opcode;
}


wstring_view Instruction::GetName() const {
    return name;
}

/*
** find the length of an op-code
*/
unsigned short Instruction::GetLength() const {

    switch (mode) {
    case OperandMode::Immediate:
    case OperandMode::ZeroPage:
    case OperandMode::IndexedIndirect:
    case OperandMode::IndirectIndexed:
    case OperandMode::ZeroPageX:
    case OperandMode::ZeroPageY:
    case OperandMode::Relative:
        return 2;

    case OperandMode::Absolute:
    case OperandMode::AbsoluteX:
    case OperandMode::AbsoluteY:
    case OperandMode::Indirect:
        return 3;

    default:
        return 1;
    }
}

LabelAccess Instruction::GetLabelAccess() const {
    return labelAccess;
}

OperandMode Instruction::GetOperandMode() const {
    return mode;
}

bool Instruction::IsImmediateMode() const {
    return mode == OperandMode::Immediate;
}

bool Instruction::IsUnsupportedInstruction() const {
    return illegal;
}

